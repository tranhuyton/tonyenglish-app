    print(f"=== PUBLISHING 10 SAT ELITE VOCAB GAMES ({sum(len(s['words']) for s in VOCAB_SETS)} WORDS) ===")
    for order_idx, vset in enumerate(VOCAB_SETS, start=1):
        assert len(vset['words']) == 50, f"{vset['key']} does not have 50 words!"
        cjson = build_vocab_game_json(vset, course_id)
        payload = {
            'course_id': course_id,
            'folder_id': folder_id,
            'title': vset['title'],
            'test_type': 'MCQ (Standard)',
            'content_json': cjson,
            'is_published': True,
            'order_index': order_idx,
        }
        existing_id = ids.get('vocab_games', {}).get(vset['key'])
        tid = None
        if existing_id:
            res = sb.table('tests').update(payload).eq('id', existing_id).execute().data
            if res:
                tid = existing_id
                print(f"  [UPDATED GAME] {vset['title']} ({vset['theme']})")
        if not tid:
            found = sb.table('tests').select('id').eq('course_id', course_id).eq('title', vset['title']).execute().data
            if found:
                tid = found[0]['id']
                sb.table('tests').update(payload).eq('id', tid).execute()
                print(f"  [UPDATED GAME] {vset['title']} ({vset['theme']})")
            else:
                tid = sb.table('tests').insert(payload).execute().data[0]['id']
                print(f"  [CREATED GAME] {vset['title']} ({vset['theme']}) -> {tid}")
        ids.setdefault('vocab_games', {})[vset['key']] = tid

    save_ids(ids)
