def build_vocab_game_json(vset, course_id):
    rng = random.Random(vset['key'])
    words = vset['words']
    questions = []
    labels = ['A', 'B', 'C', 'D']

    for idx, (word, pos, vi_mean, en_hint) in enumerate(words):
        # Pick 3 distinct distractors from the rest of the set
        others = [w[2] for j, w in enumerate(words) if j != idx and w[2] != vi_mean]
        distractors = rng.sample(others, 3)
        opts = [vi_mean] + distractors
        rng.shuffle(opts)
        correct_idx = opts.index(vi_mean)

        questions.append({
            'id': str(idx + 1),
            'content': f'{word} ({pos}) — [{en_hint}]',
            'options': opts,
            'correctAnswer': labels[correct_idx],
            'explanation': f'{word} ({pos}) = {vi_mean} ({en_hint}).',
        })

    return {
        'basicInfo': {
            'title': vset['title'],
            'category': 'game',
            'gameTheme': vset['theme'],
            'courseId': course_id,
        },
        'parts': [
            {
                'id': '1',
                'title': '',
                'sections': [
                    {
                        'id': '1',
                        'title': '',
                        'questionType': 'Trắc nghiệm',
                        'questions': questions,
                    }
                ],
            }
        ],
    }

